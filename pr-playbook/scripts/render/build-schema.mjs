#!/usr/bin/env node
// Writes pr-connpass-page/references/output.schema.json from templates/connpass-page/page.schema.json.
// Codex's --output-schema needs one self-contained strict schema, so the section contracts are
// inlined (no $ref). `--check` fails when the file is out of date (build-schema.test.mjs).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
const page = JSON.parse(
  readFileSync(new URL("pr-playbook/templates/connpass-page/page.schema.json", root), "utf8"),
);
const S = { type: "string" };
const N = { anyOf: [{ type: "string" }, { type: "null" }] };
const obj = (props) => ({
  type: "object",
  additionalProperties: false,
  required: Object.keys(props),
  properties: props,
});

export function buildOutputSchema() {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "pr-connpass-page output",
    description:
      "Generated by pr-playbook/scripts/render/build-schema.mjs from templates/connpass-page/page.schema.json. Do not edit by hand.",
    ...obj({
      title: S,
      summary: S,
      sections: { type: "array", items: { anyOf: Object.values(page.$defs) } },
      imageSlots: { type: "array", items: obj({ id: S, purpose: S, text: S }) },
      surveyQuestions: {
        type: "array",
        items: obj({
          title: S,
          answerType: { type: "string", enum: ["free_text", "checkbox", "radio", "dropdown"] },
          required: { type: "boolean" },
          options: { anyOf: [{ type: "array", items: S }, { type: "null" }] },
        }),
      },
      participantOnlyInfo: S,
      skinSource: { type: "string", enum: ["brief", "brand-guide", "gdg-design"] },
      notes: N,
    }),
  };
}

const target = new URL("pr-connpass-page/references/output.schema.json", root);
if (import.meta.url === `file://${process.argv[1]}`) {
  const text = `${JSON.stringify(buildOutputSchema(), null, 2)}\n`;
  if (process.argv.includes("--check")) {
    // Compare as JSON: Biome may reformat the file.
    if (
      JSON.stringify(JSON.parse(readFileSync(target, "utf8"))) !==
      JSON.stringify(buildOutputSchema())
    ) {
      console.error(
        "output.schema.json is out of date: run node pr-playbook/scripts/render/build-schema.mjs",
      );
      process.exit(1);
    }
  } else writeFileSync(target, text);
}
