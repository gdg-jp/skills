#!/usr/bin/env node
// Writes pr-connpass-page/references/output.schema.json from templates/connpass-page/page.schema.json.
// Codex's --output-schema needs one self-contained strict schema, so the section contracts are
// inlined (no $ref). `--check` fails when the file is out of date (build-schema.test.mjs).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
const page = JSON.parse(
  readFileSync(new URL("pr-playbook/templates/connpass-page/page.schema.json", root), "utf8"),
);
const S = { type: "string" };
const N = { anyOf: [{ type: "string" }, { type: "null" }] };
const obj = (props) => ({
  type: "object",
  additionalProperties: false,
  required: Object.keys(props),
  properties: props,
});

export function buildOutputSchema() {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "pr-connpass-page output",
    description:
      "Generated by pr-playbook/scripts/render/build-schema.mjs from templates/connpass-page/page.schema.json. Do not edit by hand.",
    ...obj({
      title: S,
      summary: S,
      sections: { type: "array", items: { anyOf: Object.values(page.$defs) } },
      imageSlots: { type: "array", items: obj({ id: S, purpose: S, text: S }) },
      surveyQuestions: {
        type: "array",
        items: obj({
          title: S,
          answerType: { type: "string", enum: ["free_text", "checkbox", "radio", "dropdown"] },
          required: { type: "boolean" },
          options: { anyOf: [{ type: "array", items: S }, { type: "null" }] },
        }),
      },
      participantOnlyInfo: S,
      skinSource: { type: "string", enum: ["brief", "brand-guide", "gdg-design"] },
      notes: N,
    }),
  };
}

/** pr-asset: one template id and the union of every template's slots (strict, all nullable). */
export function buildAssetSchema() {
  const dir = new URL("pr-playbook/templates/images/", root);
  const ids = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  const slots = {};
  for (const id of ids) {
    const schema = JSON.parse(readFileSync(new URL(`${id}/slots.schema.json`, dir), "utf8"));
    for (const [key, spec] of Object.entries(schema.slots))
      slots[key] =
        spec.type === "list" ? { anyOf: [{ type: "array", items: S }, { type: "null" }] } : N;
  }
  const sorted = Object.fromEntries(
    Object.keys(slots)
      .sort()
      .map((k) => [k, slots[k]]),
  );
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "pr-asset output",
    description:
      "Generated by pr-playbook/scripts/render/build-schema.mjs from templates/images/*/slots.schema.json. Slots the template does not use are null. Do not edit by hand.",
    ...obj({
      templateId: { type: "string", enum: ids },
      slots: obj(sorted),
      layoutVars: obj({
        titleScale: { type: "number" },
        align: { type: "string", enum: ["left", "center"] },
        emphasis: { type: "array", items: S },
      }),
      skinSource: { type: "string", enum: ["brief", "brand-guide", "gdg-design"] },
      rationaleMd: S,
    }),
  };
}

const target = new URL("pr-connpass-page/references/output.schema.json", root);
const assetTarget = new URL("pr-asset/references/output.schema.json", root);
if (import.meta.url === `file://${process.argv[1]}`) {
  // Compare as JSON on --check: Biome may reformat the files.
  const same = (file, built) =>
    JSON.stringify(JSON.parse(readFileSync(file, "utf8"))) === JSON.stringify(built);
  const outputs = [
    [target, buildOutputSchema()],
    [assetTarget, buildAssetSchema()],
  ];
  if (process.argv.includes("--check")) {
    if (outputs.some(([file, built]) => !same(file, built))) {
      console.error(
        "an output schema is out of date: run node pr-playbook/scripts/render/build-schema.mjs",
      );
      process.exit(1);
    }
  } else
    for (const [file, built] of outputs) writeFileSync(file, `${JSON.stringify(built, null, 2)}\n`);
}
